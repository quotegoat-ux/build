// Regenerates src/data/lienWaivers.ts and src/data/lienDeadlines.ts from the research files.
// Usage: node scripts/gen-lien-data.mjs [lien-waivers.json] [lien-deadlines.json]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const [waiversPath = "/mnt/project-files/research/lien-waivers.json", deadlinesPath = "/mnt/project-files/research/lien-deadlines.json"] = process.argv.slice(2);

const KINDS = ["conditional_progress", "unconditional_progress", "conditional_final", "unconditional_final"];
const CONFIDENCE = new Set(["high", "medium-high", "medium", "low"]);

const TRIGGERS = {
  first_furnishing: "first_furnishing",
  last_furnishing: "last_furnishing",
  completion: "completion",
  substantial_completion: "completion",
  last_furnishing_under_general_contract: "completion",
  month_of_work: "month_of_work",
  lien_filing: "lien_deadline",
  lien_filing_deadline: "lien_deadline",
  statement_of_account_deadline: "lien_deadline",
  lien_recorded: "lien_recorded",
  lien_filed: "lien_recorded",
};

function fail(message) {
  throw new Error(`gen-lien-data: ${message}`);
}

function waiverData(src) {
  const states = {};
  for (const [code, s] of Object.entries(src.states)) {
    const forms = {};
    const gaps = {};
    for (const kind of KINDS) {
      const f = s.forms[kind];
      if (f?.body && s.applies_to_commercial !== false) forms[kind] = { title: f.title, body: f.body, verified: f.verified === true };
      else if (f?.note) gaps[kind] = f.note;
    }
    states[code] = { citation: s.citation, notarize: s.notarize === true, witness: s.witness_required === true, forms, gaps };
  }
  const generic = {};
  for (const kind of KINDS) {
    const f = src.generic.forms[kind] ?? fail(`generic form ${kind} missing`);
    generic[kind] = { title: f.title, body: f.body, verified: f.verified === true };
  }
  return { states, generic };
}

function rule(code, kind, r, isAlternative) {
  const trigger = TRIGGERS[r.trigger];
  if (!trigger) {
    if (isAlternative) return null;
    fail(`${code}.${kind}: unknown main trigger ${r.trigger}`);
  }
  const required = r.required !== false;
  if (trigger === "month_of_work") {
    if (!Number.isInteger(r.offset_months) || !Number.isInteger(r.day_of_month)) fail(`${code}.${kind}: month_of_work needs offset_months and day_of_month`);
    return { trigger, offsetMonths: r.offset_months, dayOfMonth: r.day_of_month, required };
  }
  const hasDays = Number.isInteger(r.offset_days);
  const hasMonths = Number.isInteger(r.offset_months);
  if (hasDays === hasMonths) fail(`${code}.${kind}: needs exactly one of offset_days or offset_months`);
  return { trigger, offset: hasDays ? { days: r.offset_days } : { months: r.offset_months }, required };
}

function rules(code, kind, r) {
  if (!r) return [];
  return [rule(code, kind, r, false), ...(r.alternatives ?? []).map((a) => rule(code, kind, a, true))].filter(Boolean);
}

function deadlineData(src) {
  const out = {};
  for (const [code, s] of Object.entries(src.states)) {
    if (!CONFIDENCE.has(s.confidence)) fail(`${code}: unknown confidence ${s.confidence}`);
    out[code] = {
      citation: s.citation,
      confidence: s.confidence,
      prelim_notice: rules(code, "prelim_notice", s.prelim_notice),
      lien_filing: rules(code, "lien_filing", s.lien_filing),
      enforcement: rules(code, "enforcement", s.enforcement),
    };
  }
  return out;
}

const header = (from) => `// Generated by scripts/gen-lien-data.mjs from ${from}. Do not edit; rerun the script.\n`;
const json = (v) => JSON.stringify(v, null, 2);

const waivers = waiverData(JSON.parse(readFileSync(waiversPath, "utf8")));
writeFileSync(
  join(root, "src/data/lienWaivers.ts"),
  `${header("lien-waivers.json")}import type { StateWaiverRules, WaiverForm, WaiverKind } from "../waivers";

export const STATE_WAIVER_RULES: Partial<Record<string, StateWaiverRules>> = ${json(waivers.states)};

export const GENERIC_WAIVER_FORMS: Record<WaiverKind, WaiverForm> = ${json(waivers.generic)};
`,
);

const deadlines = deadlineData(JSON.parse(readFileSync(deadlinesPath, "utf8")));
writeFileSync(
  join(root, "src/data/lienDeadlines.ts"),
  `${header("lien-deadlines.json")}import type { StateDeadlineRules } from "../deadlines";

export const DEADLINE_RULES: Partial<Record<string, StateDeadlineRules>> = ${json(deadlines)};
`,
);

console.log(`wrote ${Object.keys(waivers.states).length} waiver states and ${Object.keys(deadlines).length} deadline states`);
